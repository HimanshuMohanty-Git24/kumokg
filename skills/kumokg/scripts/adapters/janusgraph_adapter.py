"""JanusGraph / Apache TinkerPop: ``schema.groovy`` (management API property keys, vertex/edge labels, composite
indexes), ``graph.graphson`` (GraphSON 3.0 adjacency list with typed values), ``load.groovy`` and a gremlinpython push."""
from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path
from typing import Any

from .base import BaseAdapter, Parsed, Projection, infer_type, require_driver, validate_balanced

GROOVY_TYPES = {"int": "Long.class", "float": "Double.class", "bool": "Boolean.class", "string": "String.class"}


def _typed(v: Any) -> Any:
    if isinstance(v, bool) or isinstance(v, str) or v is None:
        return v
    if isinstance(v, int):
        return {"@type": "g:Int64", "@value": v}
    if isinstance(v, float):
        return {"@type": "g:Double", "@value": v}
    return str(v)


def _gid(n: int) -> dict[str, Any]:
    return {"@type": "g:Int64", "@value": n}


def _untyped(v: Any, where: str) -> Any:
    if isinstance(v, dict):
        if set(v) != {"@type", "@value"} or v["@type"] not in ("g:Int64", "g:Int32", "g:Double", "g:Float"):
            raise ValueError(f"invalid GraphSON typed value at {where}: {v}")
        return v["@value"]
    return v


def property_key_types(proj: Projection) -> dict[str, str]:
    """JanusGraph property keys are global: one type per key name (conflicts fall back to String)."""
    values: dict[str, list[Any]] = defaultdict(list)
    for item in list(proj.nodes) + list(proj.edges):
        for k, v in item.props.items():
            values[k].append(v)
    return {k: infer_type(vs) for k, vs in sorted(values.items())}


def gremlin_push(proj: Projection, g: Any, batch: int = 50) -> dict[str, Any]:
    """Idempotent vertex + edge upsert over any TinkerPop Gremlin endpoint (JanusGraph, Neptune).

    ``g`` is a GraphTraversalSource; an object exposing ``anon`` (the ``__`` builder) may be passed instead of a
    real one so the traversal construction can be exercised without a server."""
    __ = getattr(g, "anon", None)
    if __ is None:
        from gremlin_python.process.graph_traversal import __

    stats = {"vertex_batches": 0, "edge_batches": 0}
    for i in range(0, len(proj.nodes), batch):
        t = g
        for n in proj.nodes[i:i + batch]:
            add = __.addV(n.label).property("kumo_id", n.id)
            for k, v in n.props.items():
                if v is not None and k != "kumo_id":
                    add = add.property(k, v)
            t = t.V().has(n.label, "kumo_id", n.id).fold().coalesce(__.unfold(), add)
        t.iterate()
        stats["vertex_batches"] += 1
    for i in range(0, len(proj.edges), batch):
        t = g
        for e in proj.edges[i:i + batch]:
            add = __.addE(e.type).from_(__.V().has("kumo_id", e.source)).to(__.V().has("kumo_id", e.target)).property("kumo_id", e.kumo_id)
            for k, v in e.props.items():
                if v is not None and k != "kumo_id":
                    add = add.property(k, v)
            t = t.E().has(e.type, "kumo_id", e.kumo_id).fold().coalesce(__.unfold(), add)
        t.iterate()
        stats["edge_batches"] += 1
    return stats


class JanusGraphAdapter(BaseAdapter):
    name = "janusgraph"
    title = "JanusGraph / TinkerPop"
    extra = "janusgraph"

    def write_files(self, proj: Projection, out: Path) -> None:
        keys = property_key_types(proj)
        lines = ["// JanusGraph schema generated by KumoKG. Run inside the Gremlin console: :load schema.groovy",
                 "mgmt = graph.openManagement()"]
        for k, t in keys.items():
            lines.append(f"if (!mgmt.containsPropertyKey('{k}')) mgmt.makePropertyKey('{k}').dataType({GROOVY_TYPES[t]})"
                         f".cardinality(org.janusgraph.core.Cardinality.SINGLE).make()")
        for label in proj.labels():
            lines.append(f"if (!mgmt.containsVertexLabel('{label}')) mgmt.makeVertexLabel('{label}').make()")
        for etype in proj.types():
            lines.append(f"if (!mgmt.containsEdgeLabel('{etype}')) mgmt.makeEdgeLabel('{etype}').multiplicity(org.janusgraph.core.Multiplicity.MULTI).make()")
        lines += ["if (!mgmt.containsGraphIndex('byKumoId')) mgmt.buildIndex('byKumoId', org.apache.tinkerpop.gremlin.structure.Vertex.class)"
                  ".addKey(mgmt.getPropertyKey('kumo_id')).unique().buildCompositeIndex()",
                  "if (!mgmt.containsGraphIndex('edgeByKumoId')) mgmt.buildIndex('edgeByKumoId', org.apache.tinkerpop.gremlin.structure.Edge.class)"
                  ".addKey(mgmt.getPropertyKey('kumo_id')).buildCompositeIndex()",
                  "if (!mgmt.containsGraphIndex('byName')) mgmt.buildIndex('byName', org.apache.tinkerpop.gremlin.structure.Vertex.class)"
                  ".addKey(mgmt.getPropertyKey('name')).buildCompositeIndex()",
                  "mgmt.commit()"]
        (out / "schema.groovy").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
        vid = {n.id: i + 1 for i, n in enumerate(proj.nodes)}
        out_e: dict[str, dict[str, list]] = defaultdict(lambda: defaultdict(list))
        in_e: dict[str, dict[str, list]] = defaultdict(lambda: defaultdict(list))
        eid_base = len(proj.nodes) + 1
        for j, e in enumerate(proj.edges):
            props = {k: _typed(v) for k, v in e.props.items() if v is not None}
            eid = _gid(eid_base + j)
            out_e[e.source][e.type].append({"id": eid, "inV": _gid(vid[e.target]), "properties": props})
            in_e[e.target][e.type].append({"id": eid, "outV": _gid(vid[e.source]), "properties": props})
        pid = 10 ** 9
        with open(out / "graph.graphson", "w", encoding="utf-8", newline="\n") as fh:
            for n in proj.nodes:
                vprops = {}
                for k, v in n.props.items():
                    if v is None:
                        continue
                    pid += 1
                    vprops[k] = [{"id": _gid(pid), "value": _typed(v)}]
                line = {"id": _gid(vid[n.id]), "label": n.label, "properties": vprops}
                if out_e.get(n.id):
                    line["outE"] = dict(sorted(out_e[n.id].items()))
                if in_e.get(n.id):
                    line["inE"] = dict(sorted(in_e[n.id].items()))
                fh.write(json.dumps(line, ensure_ascii=False, sort_keys=True) + "\n")
        (out / "load.groovy").write_text(
            "// Bulk-load the GraphSON 3.0 adjacency list (run after schema.groovy) from the Gremlin console:\n"
            "//   :load load.groovy\n"
            "graph.io(org.apache.tinkerpop.gremlin.structure.io.IoCore.graphson()).readGraph('graph.graphson')\n"
            "graph.tx().commit()\n"
            "g = graph.traversal()\n"
            f"assert g.V().has('kumo_id').count().next() == {len(proj.nodes)}L\n"
            f"assert g.E().has('kumo_id').count().next() == {len(proj.edges)}L\n", encoding="utf-8", newline="\n")

    def readme(self, proj: Projection) -> str:
        c = proj.counts()
        return f"""# KumoKG -> JanusGraph / TinkerPop

Graph hash `{proj.graph_hash}` · {c['nodes']} vertices · {c['edges']} edges · provenance mode `{proj.provenance_mode}`.

From `bin/gremlin.sh` with a JanusGraph `graph` opened:
```
:load schema.groovy
:load load.groovy
```
`graph.graphson` is a GraphSON 3.0 adjacency list (one vertex per line, typed `g:Int64` / `g:Double` values) that any
TinkerPop 3.x `GraphReader` can ingest. Vertex/edge ids are positional; the stable id is the `kumo_id` property
(unique composite index `byKumoId`). Live push: set `KUMOKG_GREMLIN_URL` (ws://host:8182/gremlin) and
`export --target janusgraph --push`.
"""

    def parse_bundle(self, out: Path) -> Parsed:
        syntax: dict[str, dict[str, Any]] = {}
        ids, edges = [], []
        outs: dict[int, tuple] = {}
        ins: dict[int, tuple] = {}
        vids: dict[int, str] = {}
        ok, detail = True, "GraphSON 3.0 adjacency list"
        try:
            for ln, line in enumerate((out / "graph.graphson").read_text(encoding="utf-8").splitlines(), start=1):
                v = json.loads(line)
                vid = _untyped(v["id"], f"line {ln} id")
                if not isinstance(v.get("label"), str):
                    raise ValueError(f"line {ln}: vertex label missing")
                props = v.get("properties", {})
                for k, plist in props.items():
                    if not isinstance(plist, list) or not all({"id", "value"} <= set(p) for p in plist):
                        raise ValueError(f"line {ln}: vertex property {k} must be a list of {{id, value}}")
                kid = props["kumo_id"][0]["value"]
                vids[vid] = kid
                ids.append(kid)
                for etype, lst in v.get("outE", {}).items():
                    for e in lst:
                        outs[_untyped(e["id"], "edge id")] = (vid, _untyped(e["inV"], "inV"), etype, e["properties"].get("kumo_id"))
                for etype, lst in v.get("inE", {}).items():
                    for e in lst:
                        ins[_untyped(e["id"], "edge id")] = (_untyped(e["outV"], "outV"), vid, etype)
            for eid, (s, t, etype, kid) in outs.items():
                if ins.get(eid) != (s, t, etype):
                    raise ValueError(f"edge {eid} outE/inE mismatch")
                edges.append((kid, vids.get(s, f"missing:{s}"), vids.get(t, f"missing:{t}")))
            if set(ins) != set(outs):
                raise ValueError("inE entries without matching outE")
        except (ValueError, KeyError, json.JSONDecodeError) as exc:
            ok, detail = False, str(exc)
        syntax["graph.graphson"] = {"ok": ok, "detail": detail}
        for name in ("schema.groovy", "load.groovy"):
            ok, detail, n = validate_balanced((out / name).read_text(encoding="utf-8"), "groovy")
            syntax[name] = {"ok": ok, "detail": detail}
        schema = (out / "schema.groovy").read_text(encoding="utf-8")
        if "mgmt.commit()" not in schema or "buildCompositeIndex()" not in schema:
            syntax["schema.groovy"] = {"ok": False, "detail": "schema must build composite indexes and commit"}
        return Parsed(ids, edges, syntax)

    def push_live(self, proj: Projection, env: dict[str, str], client: Any = None) -> dict[str, Any]:
        conn = None
        if client is None:
            drc = require_driver("gremlin_python.driver.driver_remote_connection", self.extra)
            from gremlin_python.process.anonymous_traversal import traversal

            (url,) = self.require_env(env, "KUMOKG_GREMLIN_URL")
            conn = drc.DriverRemoteConnection(url, "g")
            client = traversal().with_remote(conn)
        try:
            stats = gremlin_push(proj, client)
            n = client.V().has("kumo_id").count().next()
            e = client.E().has("kumo_id").count().next()
            return {"target": self.name, **stats, "nodes_in_db": n, "edges_in_db": e}
        finally:
            if conn is not None:
                conn.close()

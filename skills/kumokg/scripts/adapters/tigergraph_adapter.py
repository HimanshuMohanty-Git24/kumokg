"""TigerGraph: strictly typed ``schema.gsql`` (``CREATE VERTEX`` / ``CREATE DIRECTED EDGE`` with every FROM/TO pair),
``loading_job.gsql`` and typed CSVs (one edge file per (type, from, to) pair) + a pyTigerGraph upsert push.
GSQL keywords are case-insensitive, so colliding identifiers (e.g. ``Character``) get a ``_t`` suffix recorded in
``symbol_map.json``."""
from __future__ import annotations

import re
from pathlib import Path
from typing import Any

from .base import BaseAdapter, Parsed, Projection, columns_for, group_by, read_csv, require_driver, split_statements, write_csv


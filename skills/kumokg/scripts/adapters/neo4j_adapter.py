"""Neo4j 5.x: neo4j-admin compatible typed CSVs, ``schema.cypher`` (constraints + indexes), ``import.cypher``
(``LOAD CSV`` with type coercion) and a Bolt ``UNWIND ... MERGE`` live push."""
from __future__ import annotations

from pathlib import Path
from typing import Any

from .base import (
    BaseAdapter, Parsed, Projection, columns_for, group_by, read_csv, require_driver, validate_cypher, write_csv,
)

ID_SPACE = "KumoNode"
NEO4J_TYPES = {"int": "long", "float": "double", "bool": "boolean", "string": ""}


def _header(col: str, typ: str) -> str:
    t = NEO4J_TYPES[typ]
    return f"{col}:{t}" if t else col


def _conv(header: str, typ: str) -> str:
    ref = f"row.`{header}`"
    fn = {"int": "toInteger", "float": "toFloat", "bool": "toBoolean"}.get(typ)
    val = f"{fn}({ref})" if fn else ref
    return f"CASE {ref} WHEN '' THEN null ELSE {val} END"


def bolt_push(proj: Projection, driver: Any, database: str | None, schema_statements: list[str], batch: int = 500) -> dict[str, Any]:
    """Shared Bolt push for Neo4j and Memgraph (both speak Cypher over Bolt)."""
    stats = {"node_batches": 0, "edge_batches": 0, "statements": 0}
    with driver.session(database=database) if database else driver.session() as session:
        for st in schema_statements:
            session.run(st).consume()
            stats["statements"] += 1
        for label, nodes in group_by(proj.nodes, lambda n: n.label).items():
            q = (f"UNWIND $rows AS row MERGE (n:{ID_SPACE} {{kumo_id: row.kumo_id}}) SET n:`{label}` SET n += row.props")
            for chunk in BaseAdapter.batches(nodes, batch):
                rows = [{"kumo_id": n.id, "props": {k: v for k, v in n.props.items() if v is not None}} for n in chunk]
                session.execute_write(lambda tx, q=q, rows=rows: tx.run(q, rows=rows).consume())
                stats["node_batches"] += 1
        for etype, edges in group_by(proj.edges, lambda e: e.type).items():
            q = (f"UNWIND $rows AS row MATCH (s:{ID_SPACE} {{kumo_id: row.s}}) MATCH (t:{ID_SPACE} {{kumo_id: row.t}}) "
                 f"MERGE (s)-[r:`{etype}` {{kumo_id: row.id}}]->(t) SET r += row.props")
            for chunk in BaseAdapter.batches(edges, batch):
                rows = [{"id": e.kumo_id, "s": e.source, "t": e.target, "props": {k: v for k, v in e.props.items() if v is not None}}
                        for e in chunk]
                session.execute_write(lambda tx, q=q, rows=rows: tx.run(q, rows=rows).consume())
                stats["edge_batches"] += 1
        n = session.run(f"MATCH (n:{ID_SPACE}) RETURN count(n) AS c").single()["c"]
        e = session.run(f"MATCH (:{ID_SPACE})-[r]->(:{ID_SPACE}) WHERE r.kumo_id IS NOT NULL RETURN count(r) AS c").single()["c"]
    return {**stats, "nodes_in_db": n, "edges_in_db": e}


class Neo4jAdapter(BaseAdapter):
    name = "neo4j"
    title = "Neo4j 5.x"
    extra = "neo4j"

    def write_files(self, proj: Projection, out: Path) -> None:
        schema = [f"CREATE CONSTRAINT kumo_node_id IF NOT EXISTS FOR (n:{ID_SPACE}) REQUIRE n.kumo_id IS UNIQUE;",
                  f"CREATE FULLTEXT INDEX kumo_node_text IF NOT EXISTS FOR (n:{ID_SPACE}) ON EACH [n.name, n.aliases];"]
        imports = ["// Generated by KumoKG. Copy the CSVs into the Neo4j import directory, then run:",
                   "//   cypher-shell -f schema.cypher && cypher-shell -f import.cypher", ""]
        admin_nodes, admin_rels = [], []
        for label, nodes in group_by(proj.nodes, lambda n: n.label).items():
            cols = columns_for(nodes, ["kumo_id", "name"])
            fname = f"nodes_{label}.csv"
            headers = [f"kumo_id:ID({ID_SPACE})"] + [_header(c, t) for c, t in cols if c != "kumo_id"] + [":LABEL"]
            write_csv(out / fname, headers, ([n.id] + [n.props.get(c) for c, _ in cols if c != "kumo_id"] + [f"{label};{ID_SPACE}"]
                                             for n in nodes))
            schema.append(f"CREATE INDEX {label.lower()}_name IF NOT EXISTS FOR (n:`{label}`) ON (n.name);")
            sets = ",\n    ".join(f"n.`{c}` = {_conv(_header(c, t), t)}" for c, t in cols if c != "kumo_id")
            imports.append(f"LOAD CSV WITH HEADERS FROM 'file:///{fname}' AS row\n"
                           f"MERGE (n:{ID_SPACE} {{kumo_id: row.`kumo_id:ID({ID_SPACE})`}})\nSET n:`{label}`,\n    {sets};\n")
            admin_nodes.append(fname)
        for etype, edges in group_by(proj.edges, lambda e: e.type).items():
            cols = columns_for(edges, ["kumo_id"])
            fname = f"edges_{etype}.csv"
            headers = [f":START_ID({ID_SPACE})", f":END_ID({ID_SPACE})", ":TYPE"] + [_header(c, t) for c, t in cols]
            write_csv(out / fname, headers, ([e.source, e.target, etype] + [e.props.get(c) for c, _ in cols] for e in edges))
            schema.append(f"CREATE INDEX {etype.lower()}_kumo_id IF NOT EXISTS FOR ()-[r:`{etype}`]-() ON (r.kumo_id);")
            sets = ",\n    ".join(f"r.`{c}` = {_conv(_header(c, t), t)}" for c, t in cols if c != "kumo_id")
            imports.append(f"LOAD CSV WITH HEADERS FROM 'file:///{fname}' AS row\n"
                           f"MATCH (s:{ID_SPACE} {{kumo_id: row.`:START_ID({ID_SPACE})`}})\n"
                           f"MATCH (t:{ID_SPACE} {{kumo_id: row.`:END_ID({ID_SPACE})`}})\n"
                           f"MERGE (s)-[r:`{etype}` {{kumo_id: row.`kumo_id`}}]->(t)"
                           + (f"\nSET {sets};\n" if sets else ";\n"))
            admin_rels.append(fname)
        (out / "schema.cypher").write_text("\n".join(schema) + "\n", encoding="utf-8", newline="\n")
        (out / "import.cypher").write_text("\n".join(imports), encoding="utf-8", newline="\n")
        self._admin = ("neo4j-admin database import full kumokg --overwrite-destination "
                       + " ".join(f"--nodes={f}" for f in admin_nodes) + " "
                       + " ".join(f"--relationships={f}" for f in admin_rels))
        (out / "neo4j-admin-import.sh").write_text("#!/usr/bin/env sh\nset -e\ncd \"$(dirname \"$0\")\"\n" + self._admin + "\n",
                                                   encoding="utf-8", newline="\n")

    def readme(self, proj: Projection) -> str:
        c = proj.counts()
        return f"""# KumoKG -> Neo4j import

Graph hash `{proj.graph_hash}` · {c['nodes']} nodes · {c['edges']} relationships · provenance mode `{proj.provenance_mode}`.

## Option 1 — online (LOAD CSV)
1. Copy every `nodes_*.csv` / `edges_*.csv` into the database `import/` directory.
2. `cypher-shell -u neo4j -p <password> -f schema.cypher`
3. `cypher-shell -u neo4j -p <password> -f import.cypher`

## Option 2 — offline bulk (empty database)
`sh neo4j-admin-import.sh` (runs `neo4j-admin database import full` with typed headers; `:LABEL` uses `;` as array delimiter).

## Option 3 — live push from KumoKG
Set `KUMOKG_NEO4J_URI`, `KUMOKG_NEO4J_USER`, `KUMOKG_NEO4J_PASSWORD` in `.kumokg/.env`, then
`uv run --extra neo4j ... kumokg_cli.py export --target neo4j --push` (batched `UNWIND ... MERGE` + count parity).

Every node carries the shared label `KumoNode` and a unique `kumo_id`; relationships carry `kumo_id`, `valid_from`,
`valid_to`, `status` (bi-temporal history is preserved; superseded facts have `status = 'superseded'`).
`symbol_map.json` lists any label/type/property renames.
"""

    def parse_bundle(self, out: Path) -> Parsed:
        ids: list[str] = []
        edges: list[tuple[str, str, str]] = []
        syntax = {}
        for f in sorted(out.glob("nodes_*.csv")):
            header, rows = read_csv(f)
            key = f"kumo_id:ID({ID_SPACE})"
            syntax[f.name] = {"ok": key in header and ":LABEL" in header, "detail": "neo4j-admin header"}
            ids.extend(r[key] for r in rows)
        for f in sorted(out.glob("edges_*.csv")):
            header, rows = read_csv(f)
            ok = all(h in header for h in (f":START_ID({ID_SPACE})", f":END_ID({ID_SPACE})", ":TYPE", "kumo_id"))
            syntax[f.name] = {"ok": ok, "detail": "neo4j-admin header"}
            edges.extend((r["kumo_id"], r[f":START_ID({ID_SPACE})"], r[f":END_ID({ID_SPACE})"]) for r in rows)
        for name in ("schema.cypher", "import.cypher"):
            ok, detail, n = validate_cypher((out / name).read_text(encoding="utf-8"))
            syntax[name] = {"ok": ok, "detail": detail, "statements": n}
        return Parsed(ids, edges, syntax)

    def schema_statements(self) -> list[str]:
        return [f"CREATE CONSTRAINT kumo_node_id IF NOT EXISTS FOR (n:{ID_SPACE}) REQUIRE n.kumo_id IS UNIQUE"]

    def push_live(self, proj: Projection, env: dict[str, str], client: Any = None) -> dict[str, Any]:
        own = client is None
        if own:
            neo4j = require_driver("neo4j", self.extra)
            uri, user, pw = self.require_env(env, "KUMOKG_NEO4J_URI", "KUMOKG_NEO4J_USER", "KUMOKG_NEO4J_PASSWORD")
            client = neo4j.GraphDatabase.driver(uri, auth=(user, pw))
        try:
            return {"target": self.name, **bolt_push(proj, client, env.get("KUMOKG_NEO4J_DATABASE"), self.schema_statements())}
        finally:
            if own:
                client.close()
